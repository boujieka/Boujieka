"""Publish a Markdown document as a branded A4 PDF (Africa Energy Finance house style).

Run: python tools/publish_docs.py <source.md> <out.pdf> --title "..." --subtitle "..." [--kicker "..."] [--short "..."]

Pipeline
1. Markdown to HTML with the brand stylesheet, a cover page and a table of contents.
2. First Chromium render with hidden heading markers, used only to find the page of every heading.
3. Second render with the page numbers written into the table of contents (dot leaders).
4. Running header and footer stamped on every page except the cover, PDF bookmarks from the headings,
   and document properties set to the author.
5. Final scan of the PDF text for dashes and for words that do not belong in a publication.
Images referenced in the Markdown are resolved relative to the source file.
"""
