const DICTS: Record<Loc, Record<DictKey, string>> = { en, fr };
const STORAGE_KEY = "a360_locale";

interface LocaleCtx {
  locale: Loc;
  setLocale: (l: Loc) => void;
  t: (k: DictKey, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<LocaleCtx | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Loc>("en");

  useEffect(() => {
    try {
      const v = window.localStorage.getItem(STORAGE_KEY);
      // eslint-disable-next-line react-hooks/set-state-in-effect -- hydrate from storage after mount
      if (v === "en" || v === "fr") setLocaleState(v);
    } catch {
      /* storage unavailable */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((l: Loc) => {
    setLocaleState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage unavailable */
    }
  }, []);

  const t = useCallback(
    (k: DictKey, vars?: Record<string, string | number>) => {
      let s = DICTS[locale][k] ?? en[k] ?? k;
      if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
      return s;
    },
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): LocaleCtx {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside LocaleProvider");
  return c;
}
