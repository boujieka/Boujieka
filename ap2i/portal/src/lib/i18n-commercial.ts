const COM: Record<Locale, Record<string, string>> = { fr: commercialFR, en: commercialEN };

/** Translate a "com." key (falls back to English, then to the key itself). */
export function ct(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = COM[locale]?.[key] ?? commercialEN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
